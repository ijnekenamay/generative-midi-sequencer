DisplayController::DisplayController() {
    // Pico Tracker physical pin mappings from J7 DISPLAY Schematic (SPI1)
    pin_miso = 22; // Display RESET (DP4 -> GP22)
    pin_cs   = 20; // Display CS (DP3 -> GP20)
    pin_sck  = 26; // Display SCK (DP7 -> GP26)
    pin_mosi = 27; // Display MOSI (DP6 -> GP27)
    pin_dc   = 21; // Display D/C (DP5 -> GP21)

    // Landscape Mode standard orientation
    width = 320;
    height = 240;
    rotation = 3;
}

void DisplayController::write_cmd(uint8_t cmd) {
    gpio_put(pin_dc, 0); // DC Low = Command
    gpio_put(pin_cs, 0); // Select Display
    spi_write_blocking(spi1, &cmd, 1);
    gpio_put(pin_cs, 1); // Deselect
}

void DisplayController::write_data(uint8_t data) {
    gpio_put(pin_dc, 1); // DC High = Data
    gpio_put(pin_cs, 0);
    spi_write_blocking(spi1, &data, 1);
    gpio_put(pin_cs, 1);
}

void DisplayController::write_data_buf(const uint8_t* buf, uint32_t len) {
    gpio_put(pin_dc, 1);
    gpio_put(pin_cs, 0);
    spi_write_blocking(spi1, buf, len);
    gpio_put(pin_cs, 1);
}

void DisplayController::reset() {
    // Hardware reset pulse via GP16 (wired to LCD RST)
    gpio_put(pin_miso, 1);
    sleep_ms(5);
    gpio_put(pin_miso, 0);
    sleep_ms(20);
    gpio_put(pin_miso, 1);
    sleep_ms(150);
}

void DisplayController::init() {
    // 1. Initialize SPI1 at 48 MHz (maximum safe speed for ILI9341 on breadboard)
    spi_init(spi1, 48000000);
    
    // 2. Map SPI functions to GPIO pins
    gpio_set_function(pin_sck, GPIO_FUNC_SPI);
    gpio_set_function(pin_mosi, GPIO_FUNC_SPI);
    
    // 3. Initialize control pins as standard outputs
    gpio_init(pin_cs);
    gpio_set_dir(pin_cs, GPIO_OUT);
    gpio_put(pin_cs, 1);

    gpio_init(pin_dc);
    gpio_set_dir(pin_dc, GPIO_OUT);
    gpio_put(pin_dc, 1);
    
    // GP16 is Display Reset
    gpio_init(pin_miso);
    gpio_set_dir(pin_miso, GPIO_OUT);
    gpio_put(pin_miso, 1);

    // 4. Trigger Display Reset
    reset();

    // 5. ILI9341 Initialization Sequence
    write_cmd(0x01); // Software reset
    sleep_ms(10);
    
    write_cmd(0x28); // Display OFF
    
    // Power controls
    write_cmd(0xC0); // Power Control 1
    write_data(0x23);
    
    write_cmd(0xC1); // Power Control 2
    write_data(0x10);
    
    // VCOM controls
    write_cmd(0xC5); // VCOM Control 1
    write_data(0x3E);
    write_data(0x28);
    
    write_cmd(0xC7); // VCOM Control 2
    write_data(0x86);
    
    // Memory Access (Orientation)
    write_cmd(0x36); // MADCTL
    // Set rotation 3 (Landscape inverted, pins on left)
    write_data(0xE8); 

    write_cmd(0x3A); // COLMOD: Pixel Format Set
    write_data(0x55); // 16-bit color (RGB 565)
    
    // Frame Rate
    write_cmd(0xB1);
    write_data(0x00);
    write_data(0x18); // 79 Hz
    
    write_cmd(0xB6); // Display Function Control
    write_data(0x08);
    write_data(0x82);
    write_data(0x27);
    
    write_cmd(0x11); // Exit Sleep
    sleep_ms(120);
    
    write_cmd(0x29); // Display ON
    sleep_ms(20);
}

void DisplayController::set_address_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1) {
    write_cmd(0x2A); // Column Address Set
    write_data(x0 >> 8);
    write_data(x0 & 0xFF);
    write_data(x1 >> 8);
    write_data(x1 & 0xFF);
    
    write_cmd(0x2B); // Page Address Set
    write_data(y0 >> 8);
    write_data(y0 & 0xFF);
    write_data(y1 >> 8);
    write_data(y1 & 0xFF);
    
    write_cmd(0x2C); // Memory Write (signals color transfer)
}

void DisplayController::clear(uint16_t color) {
    fill_rect(0, 0, width, height, color);
}

void DisplayController::draw_pixel(uint16_t x, uint16_t y, uint16_t color) {
    if (x >= width || y >= height) return;
    set_address_window(x, y, x, y);
    write_data(color >> 8);
    write_data(color & 0xFF);
}

void DisplayController::fill_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color) {
    if (x >= width || y >= height) return;
    if ((x + w) > width)  w = width - x;
    if ((y + h) > height) h = height - y;
    
    set_address_window(x, y, x + w - 1, y + h - 1);
    
    // Allocate a small optimized line buffer to minimize SPI overhead
    const uint32_t chunk_size = 128; // 128 pixels * 2 bytes = 256 byte buffer
    uint8_t color_buf[chunk_size * 2];
    uint8_t hi = color >> 8;
    uint8_t lo = color & 0xFF;
    
    for (uint32_t i = 0; i < chunk_size; ++i) {
        color_buf[i * 2] = hi;
        color_buf[i * 2 + 1] = lo;
    }
    
    uint32_t total_pixels = w * h;
    gpio_put(pin_dc, 1); // Data
    gpio_put(pin_cs, 0); // Select
    
    while (total_pixels > 0) {
        uint32_t to_write = (total_pixels > chunk_size) ? chunk_size : total_pixels;
        spi_write_blocking(spi1, color_buf, to_write * 2);
        total_pixels -= to_write;
    }
    
    gpio_put(pin_cs, 1); // Deselect
}

void DisplayController::draw_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color) {
    fill_rect(x, y, w, 1, color);         // Top
    fill_rect(x, y + h - 1, w, 1, color); // Bottom
    fill_rect(x, y, 1, h, color);         // Left
    fill_rect(x + w - 1, y, 1, h, color); // Right
}

void DisplayController::draw_char(uint16_t x, uint16_t y, char c, uint16_t color, uint16_t bg_color, uint8_t scale) {
    if (c < 32 || c > 127) c = 127; // clamp to last fallback character
    uint8_t char_index = c - 32;
    
    for (int8_t row = 0; row < 8; ++row) {
        uint8_t line = font_8x8[char_index][row]; // Get row byte from font data
        for (int8_t col = 0; col < 8; ++col) {    // Expand bits horizontally
            if (line & (1 << (7 - col))) {
                if (scale == 1) {
                    draw_pixel(x + col, y + row, color);
                } else {
                    fill_rect(x + col * scale, y + row * scale, scale, scale, color);
                }
            } else if (bg_color != color) {
                // If bg color is different, draw background pixel
                if (scale == 1) {
                    draw_pixel(x + col, y + row, bg_color);
                } else {
                    fill_rect(x + col * scale, y + row * scale, scale, scale, bg_color);
                }
            }
        }
    }
}

void DisplayController::draw_text(uint16_t x, uint16_t y, const std::string& text, uint16_t color, uint16_t bg_color, uint8_t scale) {
    uint16_t curr_x = x;
    for (char c : text) {
        draw_char(curr_x, y, c, color, bg_color, scale);
        curr_x += 8 * scale; // Move cursor by font width
        if (curr_x >= width) break; // Screen clip
    }
}
